아래에 심볼릭 링크 vs 하드 링크의 차이, 구분법, 삭제/생성 방법까지 완벽 정리해드릴게요.

✅ 1. 심볼릭 링크(Symbolic Link, soft link)
📌 개념
별도의 파일로, 원본 파일의 경로를 참조함

Windows의 바로가기와 유사

원본이 삭제되면 링크는 끊어짐 (dangling link)

📌 특징
| 항목         | 설명                        |
| ---------- | ------------------------- |
| inode      | **다름** (원본과 링크가 다른 inode) |
| 크기         | 원본 경로 문자열 길이              |
| 디렉토리 링크 가능 | O                         |
| 다른 파일시스템   | O                         |


📌 생성
bash
복사
편집
ln -s 원본파일 링크이름
예:

bash
복사
편집
ln -s /etc/hosts myhosts
📌 삭제
bash
복사
편집
rm 링크이름
원본 파일에는 영향 없음

✅ 2. 하드 링크(Hard Link)
📌 개념
원본 파일의 inode를 공유하는 또 다른 파일 이름

링크가 아닌 그 자체가 원본과 동일한 파일

원본이 삭제돼도 다른 하드 링크가 존재하면 파일은 유지됨

📌 특징
| 항목         | 설명                 |
| ---------- | ------------------ |
| inode      | **같음**             |
| 크기         | 원본 파일과 동일          |
| 디렉토리 링크 가능 | ❌ (보안상 금지됨)        |
| 다른 파일시스템   | ❌ (같은 파티션 내에서만 가능) |


📌 생성
bash
복사
편집
ln 원본파일 링크이름
예:

bash
복사
편집
ln /etc/hosts myhosts_hard
📌 삭제
bash
복사
편집
rm 링크이름
모든 하드링크가 삭제되기 전까지 파일은 유지됨

✅ 3. 심볼릭 링크 vs 하드 링크 비교표
| 구분                | 심볼릭 링크      | 하드 링크      |
| ----------------- | ----------- | ---------- |
| inode 공유          | ❌ (다름)      | ✅ (같음)     |
| 원본 삭제 시           | 끊어짐 (죽은 링크) | 문제 없음      |
| 디렉토리 링크           | 가능          | 불가능        |
| 다른 파티션            | 가능          | 불가능        |
| `ls -l` 출력        | `→ 원본경로` 표시 | 일반 파일처럼 보임 |
| `stat` 또는 `ls -i` | inode 다름    | inode 같음   |


✅ 4. 링크 타입 구분 방법
🔍 방법 A: ls -l
bash
복사
편집
ls -l
심볼릭 링크는 l로 시작하고 -> 표시

sql
복사
편집
lrwxrwxrwx 1 user user   10 May 23 14:10 link.txt -> original.txt
-rw-r--r-- 2 user user 1024 May 23 14:11 hardlink.txt
🔍 방법 B: ls -i (inode 번호 확인)
bash
복사
편집
ls -i file1 file2
inode가 같으면 하드링크, 다르면 심볼릭 링크

🔍 방법 C: stat
bash
복사
편집
stat filename
File: 경로가 실제 파일 경로인지, 링크 경로인지 확인 가능

Link: 항목이 있으면 심볼릭 링크

✅ 보너스: 죽은 심볼릭 링크 찾기
bash
복사
편집
find . -type l ! -exec test -e {} \; -print
원하신다면 링크 개수 확인 스크립트, 디렉토리 내 모든 링크 리스트업도 도와드릴게요.